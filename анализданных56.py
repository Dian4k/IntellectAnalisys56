def kmedoids(X, k, max_iter=100):
    n = len(X)

    # случайные начальные медоиды
    medoids = np.random.choice(n, k, replace=False)

    # расстояния между всеми точками
    D = pairwise_distances(X)

    for _ in range(max_iter):
        # определяем кластер каждой точки
        labels = np.argmin(D[:, medoids], axis=1)

        new_medoids = medoids.copy()

        for i in range(k):
            points = np.where(labels == i)[0]

            if len(points) == 0:
                continue

            # выбираем точку с минимальной суммой
            # расстояний до остальных точек кластера
            distances = D[np.ix_(points, points)]
            new_medoids[i] = points[np.argmin(distances.sum(axis=1))]

        if np.array_equal(medoids, new_medoids):
            break

        medoids = new_medoids

    labels = np.argmin(D[:, medoids], axis=1)

    # ошибка кластеризации
    error = np.sum(D[np.arange(n), medoids[labels]] ** 2)

    return labels, medoids, error

