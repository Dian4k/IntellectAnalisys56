def add_noise(X, percent):
    X_noise = X.copy()

    n = int(len(X) * percent / 100)

    # какие объекты будем портить
    rows = np.random.choice(len(X),n,replace=False)

    for row in rows:
        # изменить от 1 до 3 координат
        count = np.random.randint(1, 4)

        cols = np.random.choice(X.shape[1],count,replace=False)

        # случайно прибавляем числа
        X_noise[row, cols] += np.random.uniform(-2,2,count)

    return X_noise

